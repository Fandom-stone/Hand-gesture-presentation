"""
Shared dataset CSV handling.

The two collectors write different rows into different files, and the two
trainers read them back, but all four do the file-level part the same way:
create with a header, tally per class, append a timestamped row, load into
arrays. Only that shared part lives here.

Their capture loops stay separate, because holding a key to rack up
single-frame samples and recording one fixed-length motion clip are genuinely
different interactions -- and so do the trainers' cleaning and evaluation,
which differ by more than their inputs.
"""

from __future__ import annotations

import csv
import time
from pathlib import Path
from typing import Dict, Sequence

import numpy as np
import pandas as pd


def ensure_csv_exists(csv_path: Path, header: Sequence[str]) -> None:
    """Create the CSV with its header row if it doesn't exist yet."""
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    if not csv_path.exists():
        with open(csv_path, "w", newline="") as f:
            csv.writer(f).writerow(list(header))


def count_existing_rows(csv_path: Path, classes: Sequence[str]) -> Dict[str, int]:
    """Per-class row counts already in the CSV, from this and prior sessions,
    so the on-screen tally reflects the whole dataset rather than today."""
    counts = {c: 0 for c in classes}
    if not csv_path.exists():
        return counts
    with open(csv_path, newline="") as f:
        for row in csv.DictReader(f):
            label = row.get("gesture")
            if label in counts:
                counts[label] += 1
    return counts


def timestamped_row(label: str, feature_vector) -> list:
    """One dataset row: label, capture time, then the features.

    The timestamp is not a feature -- training never reads it as input. It
    records WHEN each sample was captured, which is what lets the trainers
    split the data by time instead of at random (see evaluation.py).
    """
    return [label, time.time(), *feature_vector.tolist()]


def load_training_csv(
    csv_path, feature_columns: Sequence[str], written_by: str
) -> tuple[np.ndarray, np.ndarray, np.ndarray, pd.DataFrame]:
    """Load a collected dataset into (features, labels, timestamps, frame).

    `written_by` names the collector that produces this file, so a missing
    column points at the tool that should have written it.

    A file with no timestamp column still loads: row order stands in for
    capture time. That keeps datasets recorded before timestamps were added
    usable, and a time-based split on row order is still far better than a
    random one, since rows are appended in capture order.
    """
    df = pd.read_csv(csv_path)
    missing = [c for c in list(feature_columns) + ["gesture"] if c not in df.columns]
    if missing:
        raise ValueError(
            f"{Path(csv_path).name} is missing expected columns: {missing}. "
            f"Was it generated by {written_by}?"
        )
    X = df[list(feature_columns)].to_numpy(dtype=np.float32)
    y = df["gesture"].to_numpy()
    timestamps = (
        df["timestamp"].to_numpy(dtype=np.float64)
        if "timestamp" in df.columns
        else np.arange(len(df), dtype=np.float64)
    )
    return X, y, timestamps, df
